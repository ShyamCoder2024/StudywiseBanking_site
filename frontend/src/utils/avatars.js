// Get avatar by ID
export const getAvatarById = (id) => {
    return CARTOON_AVATARS.find(a => a.id === id) || CARTOON_AVATARS[0];
};

// Get random avatar
export const getRandomAvatar = () => {
    return CARTOON_AVATARS[Math.floor(Math.random() * CARTOON_AVATARS.length)];
};

// Avatar Component
export function CartoonAvatar({ avatarId, size = 48, className = '' }) {
    const avatar = getAvatarById(avatarId);

    return (
        <div
            className={`cartoon-avatar ${className}`}
            style={{
                width: size,
                height: size,
                backgroundColor: avatar.color,
                borderRadius: '50%',
                display: 'flex',
                alignItems: 'center',
                justifyContent: 'center',
                fontSize: size * 0.5,
                boxShadow: '0 4px 12px rgba(0,0,0,0.15)',
            }}
        >
            {avatar.emoji}
        </div>
    );
}

